//! Aurum Studio's local shell: a loopback-only HTTP and event-stream server,
//! written on `std::net` with no web framework.
//!
//! Godot stays the workhorse. This is the part that gives a person — and an AI
//! driving the same surface — a view of what Studio is doing: whether the
//! project is healthy, what a build is producing, which processes Studio owns,
//! and what happened, as it happens.
//!
//! ## Why a server and a browser rather than a window
//!
//! A native toolkit is a very large dependency tree, and every crate in it is
//! code that runs with the user's privileges. A local server costs no new
//! packages at all, and it has a property a window does not: it is a plain
//! HTTP interface, so tests can drive it, scripts can drive it, and an AI can
//! drive it. The shell stops being human-only.
//!
//! ## The threat model, stated plainly
//!
//! A server on the loopback interface is reachable by every process on the
//! machine, and by any web page the user's browser loads. Three things keep
//! that from being a way to run commands on this machine:
//!
//! 1. **It binds `127.0.0.1`, never `0.0.0.0`.** The port is not reachable
//!    from the network at all. This is the difference between a local tool and
//!    an open door, so it is not configurable.
//! 2. **Every request needs the session token**, which is 256 bits from the
//!    operating system's generator and is compared in constant time. A page
//!    that guesses is not slowed down; it is simply wrong.
//! 3. **The `Host` header must be a loopback literal.** This is the
//!    DNS-rebinding defence: a hostile page can point its own domain at
//!    `127.0.0.1`, and the browser will then send requests here with that
//!    domain in `Host`. Refusing a non-loopback `Host` means the rebind fails
//!    before the token is even considered.
//!
//! The token is passed in the URL so the browser can be opened directly, and
//! the page's first act is to move it into `sessionStorage` and strip it from
//! the address bar, so it does not linger in history or leak in a `Referer`.

